import sys, math, random, numpy as np
sys.path.insert(0,'.')
from ppsinger import singer_pp
def Nvec(p,k):
    S,m,q=singer_pp(p,k,random.Random(1000003*p**k)); n=len(S)
    units=np.array([math.gcd(x,m)==1 for x in range(m)]); inv=np.zeros(m,np.int64)
    for x in np.nonzero(units)[0]: inv[x]=pow(int(x),-1,m)
    N=np.zeros(m,np.int64)
    for i in range(n):
        d=np.delete((S-S[i])%m,i); du=d[units[d]]; r=(d[None,:]*inv[du][:,None])%m
        N+=np.bincount(r.ravel(),minlength=m); N[1]-=len(du)
    good=units&np.roll(units,1); good[0]=good[1]=False
    return N,good,m,q
